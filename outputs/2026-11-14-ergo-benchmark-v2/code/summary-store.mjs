/**
 * Хранилище сводки ячеек: слияние вместо перезаписи.
 *
 * Зачем отдельный модуль: `run-bench.mjs` — исполняемый скрипт верхнего уровня, его
 * нельзя импортировать в тест (импорт запускает прогон). Логика слияния вынесена
 * сюда, чтобы её можно было проверить тестом — см. `test-summary-store.mjs`.
 *
 * Дефект, который это исправляет: раннер собирал сводку в памяти процесса и писал
 * файл целиком. Драйвер вызывает раннер по одной ячейке, поэтому каждый вызов
 * затирал предыдущий, и в итоге в сводке оставалась одна запись из восьми.
 */

/**
 * Идентичность ячейки в сводке.
 *
 * Модель включена в ключ намеренно: если в один файл когда-нибудь попадут две
 * модели, ячейка `no_skill-a` у них не должна считаться одной и той же записью.
 *
 * @param row - запись сводки.
 * @returns ключ идентичности.
 */
export function summaryIdentity(row) {
  if (!row || typeof row !== 'object') return 'invalid'
  return `${row.model ?? 'unknown'}|${row.cell ?? 'unknown'}`
}

/**
 * Слить одну запись в существующую сводку.
 *
 * Запись с той же идентичностью ЗАМЕНЯЕТСЯ на месте (порядок сохраняется), новая —
 * дописывается в конец. Возвращается новый массив: входной не мутируется, иначе
 * повторный вызов с тем же входом дал бы другой результат.
 *
 * @param existing - то, что уже лежало в файле; мусор трактуется как пустая сводка.
 * @param line - новая запись ячейки.
 * @returns новая сводка.
 */
export function mergeCellSummary(existing, line) {
  const rows = Array.isArray(existing) ? existing.slice() : []
  const key = summaryIdentity(line)
  const at = rows.findIndex(row => summaryIdentity(row) === key)
  if (at === -1) rows.push(line)
  else rows[at] = line
  return rows
}
